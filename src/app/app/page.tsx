'use client';

import React, { useState } from 'react';
import { Sidebar } from '@/components/webapp/Sidebar';
import { Header } from '@/components/webapp/Header';
import { ChatStream } from '@/components/webapp/ChatStream';
import { PromptDock } from '@/components/webapp/PromptDock';
import { SettingsModal } from '@/components/webapp/SettingsModal';
import { INITIAL_CONVERSATIONS, AI_MODELS } from '@/lib/data';
import { Conversation, ChatMessage } from '@/types';
import { formatTimestamp } from '@/lib/utils';
import confetti from 'canvas-confetti';

export default function WebAppPage() {
  const [conversations, setConversations] = useState<Conversation[]>(INITIAL_CONVERSATIONS);
  const [activeConvId, setActiveConvId] = useState<string>('conv-1');
  const [selectedModelId, setSelectedModelId] = useState<string>('claude-3-5-sonnet');
  const [isCompareMode, setIsCompareMode] = useState<boolean>(true);
  const [isGenerating, setIsGenerating] = useState<boolean>(false);
  const [isSettingsOpen, setIsSettingsOpen] = useState<boolean>(false);
  const [isSidebarCollapsed, setIsSidebarCollapsed] = useState<boolean>(false);

  const activeConv = conversations.find((c) => c.id === activeConvId) || conversations[0];

  const handleNewChat = () => {
    const newId = `conv-${Date.now()}`;
    const newConv: Conversation = {
      id: newId,
      title: 'New Multi-AI Chat',
      lastUpdated: 'Just now',
      messages: [],
      modelId: selectedModelId,
      isCompareMode: isCompareMode,
    };
    setConversations([newConv, ...conversations]);
    setActiveConvId(newId);
  };

  const handleDeleteConv = (id: string) => {
    const updated = conversations.filter((c) => c.id !== id);
    setConversations(updated);
    if (activeConvId === id && updated.length > 0) {
      setActiveConvId(updated[0].id);
    }
  };

  const handleSendMessage = (promptText: string) => {
    if (!promptText.trim()) return;

    const userMsg: ChatMessage = {
      id: `msg-${Date.now()}`,
      sender: 'user',
      content: promptText,
      timestamp: formatTimestamp(new Date()),
    };

    // Update conversation with user message
    const updatedMessages = [...(activeConv?.messages || []), userMsg];
    
    // Title auto-update if first message
    const updatedTitle = activeConv?.messages.length === 0 
      ? promptText.slice(0, 30) + '...'
      : activeConv?.title || 'Multi-AI Session';

    setConversations((prev) =>
      prev.map((c) => (c.id === activeConvId ? { ...c, title: updatedTitle, messages: updatedMessages, lastUpdated: 'Just now' } : c))
    );

    setIsGenerating(true);

    // Simulate multi-model response after small delay
    setTimeout(() => {
      let assistantMsg: ChatMessage;
      const modelObj = AI_MODELS.find((m) => m.id === selectedModelId) || AI_MODELS[0];

      if (isCompareMode) {
        assistantMsg = {
          id: `msg-ai-${Date.now()}`,
          sender: 'assistant',
          content: 'Side-by-side comparative analysis generated across Claude 3.5 Sonnet and GPT-4o:',
          timestamp: formatTimestamp(new Date()),
          isComparing: true,
          modelResponses: {
            'claude-3-5-sonnet': `### Claude 3.5 Sonnet Response:\nDirect architectural solution for "${promptText}". Implements zero-cost TypeScript type safety with explicit error boundary handling.\n\n\`\`\`tsx\n// Optimized Implementation\nexport function useOrchestrator() {\n  return { status: 'ready', latency: '420ms' };\n}\n\`\`\``,
            'gpt-4o': `### GPT-4o Response:\nStreamlined resolution for "${promptText}". Focuses on sub-millisecond execution and memory-efficient garbage collection.\n\n\`\`\`ts\nconst stream = await ai.query({ prompt: "${promptText.slice(0, 20)}..." });\n\`\`\``,
          },
          latency: '780ms',
          tokens: 340,
        };
      } else {
        assistantMsg = {
          id: `msg-ai-${Date.now()}`,
          sender: 'assistant',
          modelId: selectedModelId,
          content: `Here is the response generated by **${modelObj.name}** (${modelObj.provider}):\n\n"${promptText}" requires careful consideration of latency and model parameters. EchoGPT streaming pipeline ensures fast response times.`,
          timestamp: formatTimestamp(new Date()),
          latency: '520ms',
          tokens: 210,
        };
      }

      setConversations((prev) =>
        prev.map((c) =>
          c.id === activeConvId
            ? { ...c, messages: [...c.messages, assistantMsg], lastUpdated: 'Just now' }
            : c
        )
      );

      setIsGenerating(false);
    }, 1200);
  };

  const handleClearChat = () => {
    setConversations((prev) =>
      prev.map((c) => (c.id === activeConvId ? { ...c, messages: [] } : c))
    );
  };

  const handleExportChat = () => {
    const chatExport = JSON.stringify(activeConv?.messages || [], null, 2);
    const blob = new Blob([chatExport], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `echogpt-session-${activeConvId}.json`;
    a.click();
    confetti({ particleCount: 50, spread: 60 });
  };

  return (
    <div className="h-screen w-screen bg-slate-950 text-slate-100 flex overflow-hidden font-sans selection:bg-cyan-500/30 selection:text-cyan-200">
      {/* Sidebar Navigation */}
      <Sidebar
        conversations={conversations}
        activeConvId={activeConvId}
        onSelectConv={setActiveConvId}
        onNewChat={handleNewChat}
        onDeleteConv={handleDeleteConv}
        selectedModelId={selectedModelId}
        onSelectModel={setSelectedModelId}
        onOpenSettings={() => setIsSettingsOpen(true)}
        isCollapsed={isSidebarCollapsed}
        onToggleCollapse={() => setIsSidebarCollapsed(!isSidebarCollapsed)}
      />

      {/* Main Chat Workspace */}
      <div className="flex-1 flex flex-col h-full overflow-hidden bg-grid-pattern relative">
        <Header
          activeModelId={selectedModelId}
          onSelectModel={setSelectedModelId}
          isCompareMode={isCompareMode}
          onToggleCompareMode={() => setIsCompareMode(!isCompareMode)}
          onClearChat={handleClearChat}
          onExportChat={handleExportChat}
          onOpenSettings={() => setIsSettingsOpen(true)}
        />

        {/* Chat Stream & Messages */}
        <ChatStream
          messages={activeConv?.messages || []}
          isGenerating={isGenerating}
          activeModelId={selectedModelId}
          isCompareMode={isCompareMode}
          onSendPresetPrompt={handleSendMessage}
        />

        {/* Prompt Input Dock */}
        <PromptDock
          onSendMessage={handleSendMessage}
          isGenerating={isGenerating}
          activeModelId={selectedModelId}
          onSelectModel={setSelectedModelId}
          isCompareMode={isCompareMode}
          onToggleCompareMode={() => setIsCompareMode(!isCompareMode)}
        />
      </div>

      {/* Settings Modal */}
      <SettingsModal
        isOpen={isSettingsOpen}
        onClose={() => setIsSettingsOpen(false)}
      />
    </div>
  );
}
